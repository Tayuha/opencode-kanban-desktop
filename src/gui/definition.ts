import { Schema } from "effect"
import { Plugin, Store } from "@opencode/plugin/gui"
import { defaultBoard, DEFAULT_PREFS } from "./model/board.ts"

const TagSchema = Schema.Struct({
  id: Schema.String,
  name: Schema.String,
  color: Schema.String,
})

const TaskSchema = Schema.Struct({
  id: Schema.String,
  title: Schema.String,
  projectID: Schema.String,
  projectRoot: Schema.String,
  projectName: Schema.String,
  serverID: Schema.optional(Schema.String),
  branch: Schema.String,
  baseBranch: Schema.optional(Schema.String),
  worktreePath: Schema.optional(Schema.String),
  directory: Schema.optional(Schema.String),
  categoryID: Schema.String,
  position: Schema.Number,
  tagIDs: Schema.optional(Schema.Array(Schema.String)),
  sessionID: Schema.optional(Schema.String),
  notes: Schema.optional(Schema.String),
  createdAt: Schema.Number,
  updatedAt: Schema.Number,
  archived: Schema.Boolean,
  archivedAt: Schema.optional(Schema.Number),
})

const CategorySchema = Schema.Struct({
  id: Schema.String,
  name: Schema.String,
  color: Schema.String,
  position: Schema.Number,
})

const BoardSchema = Schema.Struct({
  version: Schema.Number,
  tags: Schema.optional(Schema.Array(TagSchema)),
  tagsByProject: Schema.optional(Schema.Record(Schema.String, Schema.Array(TagSchema))),
  categories: Schema.Array(CategorySchema),
  categoriesByProject: Schema.optional(Schema.Record(Schema.String, Schema.Array(CategorySchema))),
  tasks: Schema.Array(TaskSchema),
})

const PrefsSchema = Schema.Struct({
  view: Schema.Literals(["board", "detail", "archive", "help"]),
  alignment: Schema.Literals(["fit", "scroll"]),
  columnWidth: Schema.Number,
  density: Schema.optional(Schema.Literals(["comfortable", "compact"])),
  pollMs: Schema.Number,
  autoExport: Schema.optional(Schema.Boolean),
  autoReload: Schema.optional(Schema.Boolean),
  notify: Schema.Boolean,
  pill: Schema.Boolean,
  openMode: Schema.optional(Schema.Literals(["reuse", "new", "ask"])),
  defaultCategoryID: Schema.optional(Schema.String),
  openOnCreate: Schema.Boolean,
  autoPrompt: Schema.Boolean,
  initialPrompt: Schema.String,
  lastProjectID: Schema.optional(Schema.String),
})

export type StoredPrefs = typeof PrefsSchema.Type
export type StoredBoard = typeof BoardSchema.Type

